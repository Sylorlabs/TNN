#!/bin/bash
# G1-G13 red-team battery: run each sequence on a binary, print compact rc lines.
BIN="$1"
run() {
  local tag="$1"; shift
  local out
  out=$("$BIN" G "$@" 2>/dev/null | grep "^RT " | awk '{printf "%s ", $4}' | sed 's/ $//')
  local tail
  tail=$("$BIN" G "$@" 2>/dev/null | grep "RT_END" | sed 's/.*refusals_clean=//;s/ replay=/\//;s/ ckfail=/\//')
  echo "$tag rcs=[$out] tail=$tail"
}
