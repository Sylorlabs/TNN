def write_tsv(path, rows, nfields):
    with open(path, "w", encoding="utf-8") as f:
        for r in rows:
            assert len(r) == nfields, (r[0], len(r))
            for x in r[1:]:
                assert "\t" not in x and "\n" not in x, r[0]
            f.write("\t".join(r) + "\n")

def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()

def main():
    write_tsv(os.path.join(OUT, "rta_pipeline.tsv"), RTA, 7)
    write_tsv(os.path.join(OUT, "rtb_pipeline.tsv"), RTB, 7)
    write_tsv(os.path.join(OUT, "rtd_edge.tsv"), RTD, 6)
    for fn in ("rta_pipeline.tsv", "rtb_pipeline.tsv", "rtd_edge.tsv"):
        p = os.path.join(OUT, fn)
        print(fn, sum(1 for _ in open(p)), "rows", sha(p))

if __name__ == "__main__":
    main()
