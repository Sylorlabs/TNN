def _cc_view(rng, crop, illum, exposure=1.0, noise=2):
    v = apply_illum_np(crop, ILLUM[illum], exposure)
    if noise:
        n = _sm_integers(rng, -noise, noise + 1, v.shape)
        v = np.clip(v.astype(np.int16) + n, 0, 255).astype(np.uint8)
    return v.tobytes()

def gen_colorconst(rng, family, idx):
    """family 0=normal, 1=CCN-1 extreme, 2=CCN-2 mixed-illuminant."""
    if family == 0:
        same = rng.coin(0.5)
        c1, _ = photo_crop(rng, 48, 48)
        if same:
            c2 = c1.copy()
            i1, i2 = rng.pick(["d65", "warm", "cool"]), rng.pick(["d65", "warm", "cool"])
            truth = "SAME_SURFACE"
        else:
            c2, _ = photo_crop(rng, 48, 48)
            i1, i2 = rng.pick(["d65", "warm", "cool"]), rng.pick(["d65", "warm", "cool"])
            truth = "DIFFERENT"
        f = _cc_view(rng, c1, i1) + _cc_view(rng, c2, i2)
        g = _cc_view(rng, c1, "d65") + _cc_view(rng, c2, "d65")
        return f, g, truth
    if family == 1:  # extreme illuminants + 0.55 exposure
        same = rng.coin(0.5)
        c1, _ = photo_crop(rng, 48, 48)
        c2 = c1.copy() if same else photo_crop(rng, 48, 48)[0]
        i1 = rng.pick(["xblue", "xred"]); i2 = rng.pick(["xblue", "xred"])
        truth = "SAME_SURFACE" if same else "DIFFERENT"
        f = _cc_view(rng, c1, i1, 0.55) + _cc_view(rng, c2, i2, 0.55)
        g = _cc_view(rng, c1, "d65") + _cc_view(rng, c2, "d65")
        return f, g, truth
    # CCN-2 mixed-illuminant: same crop, viewB = left warm / right cool
