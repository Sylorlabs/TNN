def photo_crop(rng, w, h):
    ph = rng.pick(photos())
    ph_h, ph_w = ph.shape[:2]
    x = rng.irange(0, ph_w - w + 1)
    y = rng.irange(0, ph_h - h + 1)
    return ph[y:y + h, x:x + w].copy(), (rng.u64() % 170, x, y)

def apply_illum_np(px, illum_xyz, exposure=1.0):
    """px: uint8 HxWx3 -> illuminant-rendered uint8 (vectorized Bradford approx
    via per-pixel apply_illuminant would be slow; use diagonal in linear RGB
    fitted per illuminant). For honesty we keep the exact Bradford on a
    32-entry LUT per channel triple? Simpler: exact per-pixel via numpy
    tensordot implementation of the Bradford chain."""
    lin = np.zeros_like(px, dtype=np.float64)
    c = px.astype(np.float64) / 255.0
    mask = c <= 0.04045
    lin[mask] = c[mask] / 12.92
    lin[~mask] = ((c[~mask] + 0.055) / 1.055) ** 2.4
    XYZ = np.tensordot(lin, np.array(XYZ_M).T, axes=1)  # HxWx3
    BR = np.array(BRAD); BRI = np.array(BRAD_I)
    src = np.array([0.95047, 1.0, 1.08883]); dst = np.array(illum_xyz)
    lms_s = np.tensordot(XYZ, BR.T, axes=1)
    wsrc = BR @ src; wdst = BR @ dst
    lms = lms_s * (wdst / wsrc)
    XYZ2 = np.tensordot(lms, BRI.T, axes=1)
    lin2 = np.tensordot(XYZ2, np.array(XYZ_MI).T, axes=1) * exposure
    lin2 = np.clip(lin2, 0, 1)
    m2 = lin2 <= 0.0031308
    out = np.zeros_like(lin2)
    out[m2] = 12.92 * lin2[m2]
    out[~m2] = 1.055 * (lin2[~m2] ** (1.0 / 2.4)) - 0.055
    return (np.clip(out, 0, 1) * 255 + 0.5).astype(np.uint8)

# ------------------------------------------------------- R2FX container
R2FX_MAGIC = 0x52324658
def write_r2fx(path, task, index, family, f_bytes, g_bytes):
    hdr = struct.pack("<8I", R2FX_MAGIC, task, index, family,
                      32, len(f_bytes), 32 + len(f_bytes), len(g_bytes))
    with open(path, "wb") as f:
        f.write(hdr); f.write(f_bytes); f.write(g_bytes)

def write_truth(path, value):
    with open(path, "w") as f:
        f.write("truth=%s\n" % value)

# ============================================================ t0 colordisc
# F = patchA(32x32 RGB) + patchB(32x32 RGB) = 6144 B
# G = patchA RGB + patchB RGB (neutral re-render, fresh noise) + 2x6 u16 spectra
CD_F = 32 * 32 * 3 * 2
CD_G = CD_F + 24

def _cd_pair(rng, s1, s2, illum_a="d65", illum_b="d65", noise=3):
    a = _render_patch(rng, spec_to_srgb(s1, illum_a), noise=noise)
    b = _render_patch(rng, spec_to_srgb(s2, illum_b), noise=noise)
    return a + b

def _cd_spectra_bytes(s1, s2):
    out = bytearray()
    for s in (s1, s2):
        for v in s:
            out += struct.pack("<H", int(round(max(0.0, min(1.0, v)) * 65535)))
    return bytes(out)

def gen_colordisc(rng, family, idx):
    """family 0=normal, 1=COL-1 metamer, 2=COL-2 illuminant-drift, 3=COL-3 gray-trap.
    Returns (f, g, truth)."""
    N = _nullspace()
    if family == 0:
        sub = idx % 3
        if sub == 0:  # SAME
            s1 = _draw_spec(rng)
            if rng.coin(0.5):
                s2 = list(s1)
            else:  # deltaE in [0.4, 1.6]
                for _ in range(200):
                    s2 = [min(0.95, max(0.05, v + rng.frange(-0.03, 0.03))) for v in s1]
                    de = delta_e_2000(rgb_to_lab(*spec_to_srgb(s1)),
                                      rgb_to_lab(*spec_to_srgb(s2)))
                    if 0.4 <= de <= 1.6:
                        break
                else:
                    raise RuntimeError("CD normal-SAME search failed idx=%d" % idx)
            truth = "SAME"
        else:  # DIFFERENT graded
            band = [(10, 28), (4, 10), (2.4, 4)][sub - 1]
            for _ in range(500):
                s1 = _draw_spec(rng); s2 = _draw_spec(rng)
                de = delta_e_2000(rgb_to_lab(*spec_to_srgb(s1)),
                                  rgb_to_lab(*spec_to_srgb(s2)))
                if band[0] <= de < band[1] and spec_l1_u16(s1, s2) >= 40000:
                    break
            else:
                raise RuntimeError("CD normal-DIFF search failed idx=%d" % idx)
            truth = "DIFFERENT"
        f = _cd_pair(rng, s1, s2)
        g = _cd_pair(rng, s1, s2) + _cd_spectra_bytes(s1, s2)
        return f, g, truth
    if family == 1:  # COL-1 metamer: truth DIFFERENT, RGB Euclid < 15
        for _ in range(2000):
            s1 = _draw_spec(rng)
            z = np.array([rng.frange(-0.35, 0.35) for _ in range(3)])
            s2 = np.clip(np.array(s1) + _NN @ z, 0.05, 0.95)
            # small RGB-visible nudge to land deltaE in [2.6, 8]
            s2 = np.clip(s2 + np.array([rng.frange(-0.02, 0.02) for _ in range(6)]),
                         0.05, 0.95)
            s2 = list(s2)
            de = delta_e_2000(rgb_to_lab(*spec_to_srgb(s1)),
                              rgb_to_lab(*spec_to_srgb(s2)))
            re_ = rgb_euclid(spec_to_srgb(s1), spec_to_srgb(s2))
            if 2.6 <= de <= 8.0 and re_ < 15 and spec_l1_u16(s1, s2) >= 40000:
                break
        else:
            raise RuntimeError("COL-1 search failed idx=%d" % idx)
        f = _cd_pair(rng, s1, s2)
        g = _cd_pair(rng, s1, s2) + _cd_spectra_bytes(s1, s2)
        return f, g, "DIFFERENT"
    if family == 2:  # COL-2 illuminant-drift: truth SAME, B under warm
        s1 = _draw_spec(rng); s2 = list(s1)
        f = _cd_pair(rng, s1, s2, illum_a="d65", illum_b="warm")
        g = _cd_pair(rng, s1, s2) + _cd_spectra_bytes(s1, s2)
        return f, g, "SAME"
    # COL-3 gray-trap: truth DIFFERENT (dE 2.6..5), RGB Euclid < 25, near-gray.
    # Nullspace move gives the spectral separation (challenge path); a +-0.12
    # RGB-visible nudge lands deltaE in the band (pilot: 15% hit rate).
    for _ in range(3000):
        g0 = rng.frange(0.35, 0.65)
        s1 = [min(0.95, max(0.05, g0 + rng.frange(-0.04, 0.04))) for _ in range(6)]
        z = np.array([rng.frange(-0.3, 0.3) for _ in range(3)])
        s2 = np.clip(np.array(s1) + _NN @ z, 0.05, 0.95)
        s2 = np.clip(s2 + np.array([rng.frange(-0.12, 0.12) for _ in range(6)]),
                     0.05, 0.95)
        s2 = list(s2)
        c1, c2 = spec_to_srgb(s1), spec_to_srgb(s2)
        de = delta_e_2000(rgb_to_lab(*c1), rgb_to_lab(*c2))
        re_ = rgb_euclid(c1, c2)
        sat = max(max(c1) - min(c1), max(c2) - min(c2))
        if 2.6 <= de <= 5.0 and re_ < 25 and sat < 40 and spec_l1_u16(s1, s2) >= 40000:
            break
    else:
        raise RuntimeError("COL-3 search failed idx=%d" % idx)
    f = _cd_pair(rng, s1, s2)
    g = _cd_pair(rng, s1, s2) + _cd_spectra_bytes(s1, s2)
    return f, g, "DIFFERENT"

