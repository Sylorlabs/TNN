# ============================================================ t2 shapetrans
# F = 96x96 u8 grayscale = 9216 B ; G = 48x48 u8 quadrant crop = 2304 B
SH_F = 96 * 96
SH_G = 48 * 48
SH_CLASSES = ["CIRCLE", "TRIANGLE", "SQUARE"]

def _raster(cls, cx, cy, scale, rot, size, fg):
    n = size * 3
    ys, xs = np.mgrid[0:n, 0:n].astype(np.float64) / 3.0
    dx = xs - cx; dy = ys - cy
    ca, sa = math.cos(rot), math.sin(rot)
    lx = dx * ca + dy * sa; ly = -dx * sa + dy * ca
    if cls == 0:  # circle
        inside = lx * lx + ly * ly <= (scale / 2) ** 2
    elif cls == 2:  # square
        inside = (np.abs(lx) <= scale / 2) & (np.abs(ly) <= scale / 2)
    else:  # triangle: equilateral, pointing up, centroid at origin
        R = scale / 2
        v = [(R * math.cos(a), R * math.sin(a))
             for a in (-math.pi / 2, math.pi / 6, 5 * math.pi / 6)]
        (x0, y0), (x1, y1), (x2, y2) = v
        d = (y1 - y2) * (x0 - x2) + (x2 - x1) * (y0 - y2)
        l0 = ((y1 - y2) * (lx - x2) + (x2 - x1) * (ly - y2)) / d
        l1 = ((y2 - y0) * (lx - x2) + (x0 - x2) * (ly - y2)) / d
        l2 = 1 - l0 - l1
        inside = (l0 >= 0) & (l1 >= 0) & (l2 >= 0)
    cov = inside.reshape(size, 3, size, 3).mean(axis=(1, 3))
    return cov

def _shape_frame(rng, cls, cx, cy, scale, rot, size, bg, fg, noise=4):
    cov = _raster(cls, cx, cy, scale, rot, size, fg)
    img = bg * (1 - cov) + fg * cov
    if noise:
        img += _sm_integers(rng, -noise, noise + 1, img.shape)
    return np.clip(img, 0, 255).astype(np.uint8)

def gen_shapetrans(rng, family, idx):
    """family 0=normal, 1=SHP-1 occlusion-bar, 2=SHP-2 distractor-blob,
    3=SHP-3 low-contrast+clutter."""
    if family == 0:
        cls = idx % 3
    else:
        cls = rng.irange(0, 3)
    scale = rng.frange(30, 44)
    rot = rng.frange(0, 2 * math.pi)
    cx = 48 + rng.frange(-14, 14); cy = 48 + rng.frange(-14, 14)
    truth = SH_CLASSES[cls]
    ph, _ = photo_crop(rng, 96, 96)
    bg = (np.asarray(Image.fromarray(ph).convert("L"), dtype=np.float64)) * 0.45
    fg = 235
    if family == 3:
        bg = np.asarray(Image.fromarray(ph).convert("L"), dtype=np.float64)  # full clutter
        fg = 150
    img = _shape_frame(rng, cls, cx, cy, scale, rot, 96, bg, fg)
    if family == 1:  # occlusion bar: solid dark bar across the shape
        by = int(cy + rng.frange(-8, 8))
        img[max(0, by - 7):min(96, by + 7), :] = 20
    if family == 2:  # distractor blob: second same-color filled circle
        for _ in range(20):
            bx = rng.frange(16, 80); by = rng.frange(16, 80)
            if math.hypot(bx - cx, by - cy) > scale:
                break
        cov = _raster(0, bx, by, scale * rng.frange(0.7, 1.0), 0.0, 96, fg)
        img = np.clip(bg * (1 - cov) + fg * cov, 0, 255)
        # redraw target shape on top (target drawn over distractor where overlapping)
        img = _shape_frame(rng, cls, cx, cy, scale, rot, 96, img.astype(np.float64), fg, noise=0)
        img = np.clip(img.astype(np.int16) + _sm_integers(rng, -4, 5, img.shape),
                      0, 255).astype(np.uint8)
    f = img.tobytes()
    # G: clean controlled re-render of the target class, centered to fit fully
    # in the 48x48 span (the F's quadrant position could clip a radius-44
    # shape at the span edge, breaking the ray-profile challenge).
    gbg = np.full((48, 48), 100.0)
    gimg = _shape_frame(rng, cls, 24, 24, 16, rot, 48, gbg, 235, noise=2)
    g = gimg.tobytes()
    assert len(f) == SH_F and len(g) == SH_G
    return f, g, truth

# ============================================================ audio helpers
RATE = 16000
AU_N = 32000  # 2.0 s
AU_F = AU_N   # F bytes = 64000 (int16)
AU_G = AU_N

def _ramps(n, ms=20):
    r = int(RATE * ms / 1000)
    w = np.ones(n)
    t = np.arange(r) / r
    w[:r] = 0.5 - 0.5 * np.cos(math.pi * t)
    w[-r:] = 0.5 - 0.5 * np.cos(math.pi * t[::-1])
    return w

def synth_tone(freq, dur, harms, rng, glide_to=None):
    """harms: list of (k, amp, phase). glide_to: end freq for linear glide."""
    n = int(RATE * dur)
    t = np.arange(n) / RATE
    if glide_to is None:
        ph = 2 * math.pi * freq * t
    else:
        fi = freq + (glide_to - freq) * t / dur
        ph = 2 * math.pi * np.cumsum(fi) / RATE
    sig = np.zeros(n)
    for k, a, pha in harms:
        sig += a * np.sin(k * ph + pha)
    sig *= _ramps(n)
    return sig

def _norm_harms(harms, peak=12000):
    sig = None
    return harms

def tone_bytes(sig):
    sig = sig / max(1e-9, np.abs(sig).max()) * 12000
    return np.clip(sig, -32768, 32767).astype("<i2").tobytes()

# ============================================================ t3 pitchdisc
# F = toneA(0-0.9s) + gap + toneB(1.0-1.9s) [+ pad] = 32000 int16
# G = clean re-render of the same two tones at TRUE endpoint freqs
PTC_GAP0, PTC_GAP1 = 14400, 16000
PTC_B0, PTC_B1 = 16000, 30400

def _ptc_render(fa, fb, harms_a, harms_b, rng, glide_a=None, glide_b=None):
    buf = np.zeros(AU_N)
    buf[0:PTC_GAP0] = synth_tone(fa, 0.9, harms_a, rng,
                                 glide_to=glide_a[1] if glide_a else None)
    bdur = (PTC_B1 - PTC_B0) / RATE
    buf[PTC_B0:PTC_B1] = synth_tone(fb, bdur, harms_b, rng,
                                    glide_to=glide_b[1] if glide_b else None)
    return buf

def _ptc_harms(rng, distractor=False):
    if distractor:
        # 0.6x 2nd + 0.3x 3rd, adversarial phase pi/2 on the 2nd (extra
        # zero-crossings verified in pilot; phase is not frozen by the spec)
        return [(1, 1.0, rng.uniform() * 6.283),
                (2, 0.6, math.pi / 2), (3, 0.3, rng.uniform() * 6.283)]
    return [(1, 1.0, rng.uniform() * 6.283),
            (2, 0.3, rng.uniform() * 6.283),
            (3, 0.15, rng.uniform() * 6.283)]

def _ptc_truth(fa, fb):
    r = (fb - fa) / fa
    if abs(r) < 0.005: return "SAME"
    return "HIGHER" if r > 0 else "LOWER"

def gen_pitchdisc(rng, family, idx):
    """family 0=normal, 1=PTC-1 near-threshold, 2=PTC-2 glide, 3=PTC-3 harmonic."""
    fa = rng.frange(220, 660)
    if family == 0:
        sub = idx % 3
        if sub == 0:
            fb = fa * (1 + rng.frange(-0.0045, 0.0045))
        elif sub == 1:
            fb = fa * (1 + rng.frange(0.0055, 0.25))
        else:
            fb = fa * (1 - rng.frange(0.0055, 0.25))
        fbuf = _ptc_render(fa, fb, _ptc_harms(rng), _ptc_harms(rng), rng)
        gbuf = _ptc_render(fa, fb, _ptc_harms(rng), _ptc_harms(rng), rng)
        return tone_bytes(fbuf), tone_bytes(gbuf), _ptc_truth(fa, fb)
    if family == 1:  # near-threshold straddle
        sub = rng.irange(0, 3)
        if sub == 0:
            fb = fa * (1 + rng.pick([-1, 1]) * rng.frange(0.0015, 0.0045))
        elif sub == 1:
            fb = fa * (1 + rng.frange(0.0055, 0.0085))
        else:
            fb = fa * (1 - rng.frange(0.0055, 0.0085))
        fbuf = _ptc_render(fa, fb, _ptc_harms(rng), _ptc_harms(rng), rng)
        gbuf = _ptc_render(fa, fb, _ptc_harms(rng), _ptc_harms(rng), rng)
        return tone_bytes(fbuf), tone_bytes(gbuf), _ptc_truth(fa, fb)
    if family == 2:  # glide-through-threshold; truth from endpoint ratio
        which = rng.irange(0, 2)  # which tone glides
        delta = rng.frange(0.015, 0.03) * rng.pick([-1, 1])
        if which == 0:
            fbuf = _ptc_render(fa, fa, _ptc_harms(rng), _ptc_harms(rng), rng,
                               glide_a=(fa, fa * (1 + delta)))
            gbuf = _ptc_render(fa * (1 + delta), fa, _ptc_harms(rng),
                               _ptc_harms(rng), rng)
            truth = _ptc_truth(fa * (1 + delta), fa)
        else:
            fbuf = _ptc_render(fa, fa, _ptc_harms(rng), _ptc_harms(rng), rng,
                               glide_b=(fa, fa * (1 + delta)))
            gbuf = _ptc_render(fa, fa * (1 + delta), _ptc_harms(rng),
                               _ptc_harms(rng), rng)
            truth = _ptc_truth(fa, fa * (1 + delta))
        return tone_bytes(fbuf), tone_bytes(gbuf), truth
    # PTC-3 harmonic distractor on tone B
    sub = rng.irange(0, 3)
    if sub == 0:
        fb = fa * (1 + rng.frange(-0.004, 0.004))
    elif sub == 1:
        fb = fa * (1 + rng.frange(0.01, 0.2))
    else:
        fb = fa * (1 - rng.frange(0.01, 0.2))
    fbuf = _ptc_render(fa, fb, _ptc_harms(rng), _ptc_harms(rng, distractor=True), rng)
    gbuf = _ptc_render(fa, fb, _ptc_harms(rng), _ptc_harms(rng), rng)
    return tone_bytes(fbuf), tone_bytes(gbuf), _ptc_truth(fa, fb)

# ============================================================ t4 timbredisc
# F = 2.0 s tone at 440 Hz with harmonic profile ; G = clean re-render
TMB_CLASSES = ["PURE", "BRIGHT", "DARK", "RICH"]
# formation bins on spectral centroid (Hz); calibrated to the profiles below
TMB_BINS = [520, 950, 1550]  # <520 PURE, <950 DARK, <1550 RICH, else BRIGHT
# challenge/truth templates in POWER ratios (p2, p3) = ((a2/a1)^2, (a3/a1)^2),
# x1000. Power ratios match what the Zag Goertzel challenge measures
# (Goertzel power is proportional to amplitude squared), so truth is defined
# in the challenge's own units: DARK (0.28^2, 0.08^2), RICH (0.8^2, 0.62^2),
# BRIGHT ((0.7/0.5)^2, (0.8/0.5)^2).
TMB_TMPL = {
    "PURE": (0, 0),
    "DARK": (78, 6),
    "RICH": (640, 384),
    "BRIGHT": (1960, 2560),
}
TMB_PROFILES = {
    "PURE": {1: 1.0},
    "DARK": {1: 1.0, 2: 0.28, 3: 0.08},
    "RICH": {1: 1.0, 2: 0.80, 3: 0.62, 4: 0.48, 5: 0.36, 6: 0.27},
    "BRIGHT": {1: 0.5, 2: 0.7, 3: 0.8, 4: 0.9, 5: 1.0, 6: 0.9, 7: 0.8, 8: 0.7},
}

def _tmb_centroid(profile):
    num = sum(k * a for k, a in profile.items())
    den = sum(profile.values())
    return 440.0 * num / den

def _tmb_template_class(profile):
    a1 = profile.get(1, 1e-9)
    p2 = int(round((profile.get(2, 0.0) / a1) ** 2 * 1000))
    p3 = int(round((profile.get(3, 0.0) / a1) ** 2 * 1000))
    best, bd = None, 1e18
    for c, (t2, t3) in TMB_TMPL.items():
        d = (p2 - t2) ** 2 + (p3 - t3) ** 2
        if d < bd: bd, best = d, c
    return best

def _tmb_bin(cent):
    if cent < TMB_BINS[0]: return "PURE"
    if cent < TMB_BINS[1]: return "DARK"
    if cent < TMB_BINS[2]: return "RICH"
    return "BRIGHT"

def _tmb_harms(profile, rng):
    return [(k, a, rng.uniform() * 6.283) for k, a in sorted(profile.items())]

def _tmb_render(profile, rng):
    return synth_tone(440.0, 2.0, _tmb_harms(profile, rng), rng)

def _interp_profile(pa, pb, lam):
    ks = set(pa) | set(pb)
    return {k: (1 - lam) * pa.get(k, 0.0) + lam * pb.get(k, 0.0) for k in ks}

def gen_timbredisc(rng, family, idx):
    """family 0=normal, 1=TMB-1 boundary-straddle, 2=TMB-2 harmonic-boost,
    3=TMB-3 distractor."""
    if family == 0:
        cls = TMB_CLASSES[idx % 4]
        profile = dict(TMB_PROFILES[cls])
        truth = cls
    elif family == 1:  # boundary straddle: centroid within +-8% of a bin boundary,
        # truth = template class on the far side of the boundary
        b = rng.pick(TMB_BINS)
        pairs = {520: ("PURE", "DARK"), 950: ("DARK", "RICH"), 1550: ("RICH", "BRIGHT")}
        ca, cb = pairs[b]
        for _ in range(300):
            lam = rng.frange(0.05, 0.95)
            profile = _interp_profile(TMB_PROFILES[ca], TMB_PROFILES[cb], lam)
            cent = _tmb_centroid(profile)
            tcls = _tmb_template_class(profile)
            bcls = _tmb_bin(cent)
            if abs(cent - b) / b <= 0.08 and tcls != bcls:
                break
        else:
            raise RuntimeError("TMB-1 search failed")
        truth = tcls
    elif family == 2:  # harmonic-boost x1.15 on 2nd: template flips, bin stays
        # (power-ratio template space; base just DARK of the DARK/RICH boundary)
        for _ in range(300):
            a2 = rng.frange(0.58, 0.66); a3 = rng.frange(0.32, 0.38)
            profile = {1: 1.0, 2: a2, 3: a3}
            boosted = {1: 1.0, 2: a2 * 1.15, 3: a3}
            if (_tmb_template_class(profile) == "DARK"
                    and _tmb_template_class(boosted) == "RICH"
                    and _tmb_bin(_tmb_centroid(profile)) == "DARK"
                    and _tmb_bin(_tmb_centroid(boosted)) == "DARK"):
                break
        else:
            raise RuntimeError("TMB-2 search failed")
        profile = boosted
        truth = "RICH"
    else:  # TMB-3 distractors
        sub = rng.irange(0, 4)
        if sub == 0:  # BRIGHT weak-fundamental
            profile = {1: 0.2, 2: 0.7, 3: 0.8, 4: 0.9, 5: 1.0, 6: 0.9, 7: 0.8, 8: 0.7}
        elif sub == 1:  # DARK extra-3rd (+0.85 -> template flips to RICH)
            profile = {1: 1.0, 2: 0.28, 3: 0.85}
        elif sub == 2:  # RICH pushed-bright (k>=4 x3.0 -> centroid crosses 1550)
            profile = {1: 1.0, 2: 0.8, 3: 0.62, 4: 1.44, 5: 1.08, 6: 0.81}
        else:  # near-PURE faint-2nd (0.2)
            profile = {1: 1.0, 2: 0.2}
        truth = _tmb_template_class(profile)
    fbuf = _tmb_render(profile, rng)
    gbuf = _tmb_render(profile, rng)
    return tone_bytes(fbuf), tone_bytes(gbuf), truth

# ============================================================ t5 motiondir
# F = 50 frames 32x32 u8 = 51200 B ; G = 50 frames clean high-contrast
MOT_F = 50 * 32 * 32
MOT_G = MOT_F
MOT_DIRS = ["N", "NE", "E", "SE", "S", "SW", "W", "NW"]
MOT_VEC = {"N": (0, -2), "NE": (2, -2), "E": (2, 0), "SE": (2, 2),
           "S": (0, 2), "SW": (-2, 2), "W": (-2, 0), "NW": (-2, -2),
           "STILL": (0, 0)}

def _mot_region(rng):
    ph = rng.pick(photos())
    ph_h, ph_w = ph.shape[:2]
    x = rng.irange(0, ph_w - 48 + 1); y = rng.irange(0, ph_h - 48 + 1)
    gray = np.asarray(Image.fromarray(ph[y:y + 48, x:x + 48]).convert("L"),
                      dtype=np.float64)
    return gray

def _mot_frames(region, direction, nframes, step_scale=1.0, contrast=1.0,
                rng=None, flicker=None, blob=None):
    """Render nframes of 32x32 from a 48x48 region; window moves per direction
    with wraparound in the 16px slack. flicker=(frac, mdir): frac of frames
    show the misleading-direction offset. blob=(mdir): bright blob moving mdir."""
    dx, dy = MOT_VEC[direction]
    dx, dy = dx * step_scale, dy * step_scale
    mdx, mdy = (MOT_VEC[flicker[1]][0] * step_scale,
                MOT_VEC[flicker[1]][1] * step_scale) if flicker else (0, 0)
    sx = rng.frange(0, 16) if rng else 4.0
    sy = rng.frange(0, 16) if rng else 4.0
    mean = region.mean()
    reg = mean + (region - mean) * contrast
    reg = np.clip(reg, 0, 255)
    frames = []
    bx, by = (rng.frange(0, 32) if rng else 8.0), (rng.frange(0, 32) if rng else 8.0)
    for t in range(nframes):
        if flicker and rng.uniform() < flicker[0]:
            wx = (sx + mdx * t) % 16; wy = (sy + mdy * t) % 16
        else:
            wx = (sx + dx * t) % 16; wy = (sy + dy * t) % 16
        ix, iy = int(wx), int(wy)
        fr = reg[iy:iy + 32, ix:ix + 32].copy()
        if blob is not None:
            bdx, bdy = MOT_VEC[blob]
            px = int((bx + bdx * t) % 32); py = int((by + bdy * t) % 32)
            fr[max(0, py - 4):py + 4, max(0, px - 4):px + 4] = 250
        if rng:
            fr += _sm_integers(rng, -3, 4, fr.shape)
        frames.append(np.clip(fr, 0, 255).astype(np.uint8))
    return frames

def _mot_high_contrast(frames):
    out = []
    for fr in frames:
        f = fr.astype(np.float64)
        lo, hi = f.min(), f.max()
        if hi - lo < 1: out.append(fr); continue
        out.append((((f - lo) / (hi - lo)) * 255).astype(np.uint8))
    return out

def gen_motiondir(rng, family, idx):
    """family 0=normal, 1=MOT-1 reversed, 2=MOT-2 flicker, 3=MOT-3 camouflaged."""
    region = _mot_region(rng)
    if family == 0:
        sub = idx % 9
        direction = "STILL" if sub == 8 else MOT_DIRS[sub]
        F = _mot_frames(region, direction, 50, rng=rng)
        G = _mot_high_contrast(_mot_frames(region, direction, 50, rng=rng))
        truth = direction
    elif family == 1:  # reversed video; truth = true direction
        direction = rng.pick(MOT_DIRS)
        fwd = _mot_frames(region, direction, 100, rng=rng)
        F = fwd[49::-1]  # frames 49..0 : shown motion is reverse(direction)
        G = _mot_high_contrast(_mot_frames(region, direction, 50, rng=rng))
        truth = direction
    elif family == 2:  # flicker + second motion; truth = dominant
        direction = rng.pick(MOT_DIRS)
        mdir = rng.pick([d for d in MOT_DIRS if d != direction])
        F = _mot_frames(region, direction, 50, rng=rng,
                        flicker=(0.30, mdir), blob=mdir)
        G = _mot_high_contrast(_mot_frames(region, direction, 50, rng=rng))
        truth = direction
    else:  # camouflaged: 25% contrast, 1px/frame
        direction = rng.pick(MOT_DIRS)
        F = _mot_frames(region, direction, 50, step_scale=0.5, contrast=0.25, rng=rng)
        G = _mot_high_contrast(_mot_frames(region, direction, 50, rng=rng))
        truth = direction
    f = b"".join(fr.tobytes() for fr in F)
    g = b"".join(fr.tobytes() for fr in G)
    assert len(f) == MOT_F and len(g) == MOT_G
    return f, g, truth

