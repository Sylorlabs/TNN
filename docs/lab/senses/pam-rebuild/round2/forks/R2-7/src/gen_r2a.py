# ---------------------------------------------------------------- PRNG
MASK64 = (1 << 64) - 1
C1 = 0x9E3779B97F4A7C15
C2 = 0xBF58476D1CE4E5B9

def splitmix64(state):
    state = (state + C1) & MASK64
    z = state
    z = ((z ^ (z >> 30)) * C2) & MASK64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
    return z ^ (z >> 31)

class Rng:
    def __init__(self, seed):
        self.s = seed & MASK64
    def u64(self):
        self.s = (self.s + C1) & MASK64
        z = self.s
        z = ((z ^ (z >> 30)) * C2) & MASK64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
        return z ^ (z >> 31)
    def uniform(self):
        return (self.u64() >> 11) * (1.0 / (1 << 53))
    def frange(self, lo, hi):
        return lo + (hi - lo) * self.uniform()
    def irange(self, lo, hi):  # [lo, hi)
        return lo + self.u64() % (hi - lo)
    def pick(self, seq):
        return seq[self.u64() % len(seq)]
    def coin(self, p=0.5):
        return self.uniform() < p

def stream_seed(master, stream, index):
    h = splitmix64((master ^ (stream * C1)) & MASK64)
    return splitmix64((h ^ (index * C2)) & MASK64)

def _sm_integers(rng, low, high, shape):
    """Deterministic integer noise in [low, high) from pure splitmix64.

    Replaces np.random.default_rng: every draw comes from the fixture's
    splitmix stream, so the suite is bit-reproducible without NumPy's
    version-dependent RNG. Uses np.fromiter to batch the Python-level draws.
    """
    n = 1
    for d in shape:
        n *= d
    span = high - low
    vals = np.fromiter((rng.u64() for _ in range(n)), dtype=np.uint64, count=n)
    return (low + (vals % np.uint64(span))).astype(np.int16).reshape(shape)

