#!/usr/bin/env python3
"""Build step/corpus/ERROR_INVENTORY.md from the frozen English corpus.

Mechanical inventory (model text vs trainer-supplied input claims, all 240 ids):
- E_dump: dump VALUE != supplied claim
- E_obs: teach OBS_VALUE != supplied claim
- E_prb: teach PROBE_VALUE != supplied claim
- inconsistent: obs_value != probe_value for the same id
- distract_value != obs_value (by design: competing directive)
- integer-in-text agreement: dump sentence / observation / distractor / probe
  text contains its asserted integer value
- per-false-id classification: reproduced vs flagged/corrected (mechanical:
  value==supplied -> reproduced; value==true and !=supplied -> corrected;
  semantic hedge-signal scan)
- explicit comparison with the toy step run's 0/240.
Writes step/corpus/ERROR_INVENTORY.md. Pure analysis of frozen data.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))  # step/build
STEP = os.path.dirname(HERE)                        # step
CJ = os.path.join(STEP, "corpus", "corpus.json")

corpus = json.load(open(CJ))
meta = corpus["meta"]
FM = corpus["fact_meta"]
FALSE_IDS = corpus["false_ids"]
DUMP = corpus["dump"]
TEACH = corpus["teach"]
SHA = open(os.path.join(STEP, "corpus", "SHA256.txt")).read().strip()

def supplied(i): return FM[str(i)]["supplied"]
def true(i): return FM[str(i)]["true"]

E_dump = [i for i in range(240) if DUMP[i]["value"] != supplied(i)]
E_obs = [i for i in range(240) if TEACH[i]["obs_value"] != supplied(i)]
E_prb = [i for i in range(240) if TEACH[i]["probe_value"] != supplied(i)]
INCONS = [i for i in range(240) if TEACH[i]["obs_value"] != TEACH[i]["probe_value"]]
DIST_EQ_OBS = [i for i in range(240) if TEACH[i]["distract_value"] == TEACH[i]["obs_value"]]

def text_has_value(text, v):
    # integer-in-text: substring match, same method as the corpus.json
    # embedded inventory and the toy run (mechanical, content-neutral)
    return str(v) in text

missing = []
for i in range(240):
    if not text_has_value(DUMP[i]["sentence"], DUMP[i]["value"]):
        missing.append(("dump", i))
    if not text_has_value(TEACH[i]["observation"], TEACH[i]["obs_value"]):
        missing.append(("obs", i))
    if not text_has_value(TEACH[i]["distractor"], TEACH[i]["distract_value"]):
        missing.append(("distractor", i))
    if not text_has_value(TEACH[i]["probe"], TEACH[i]["probe_value"]):
        missing.append(("probe", i))

HEDGE = re.compile(r"(?i)\b(actually|incorrect|however|disputed|false\b|error|mistake|correction|correcting)\b")
def hedge_scan(text):
    return bool(HEDGE.search(text))

# per-false-id classification
rows = []
for i in FALSE_IDS:
    s = supplied(i); t = true(i)
    dv, ov, pv = DUMP[i]["value"], TEACH[i]["obs_value"], TEACH[i]["probe_value"]
    texts = [DUMP[i]["sentence"], TEACH[i]["observation"],
             TEACH[i]["distractor"], TEACH[i]["probe"]]
    hedge = any(hedge_scan(x) for x in texts)
    other_int = False
    for x, v in zip(texts, (dv, ov, TEACH[i]["distract_value"], pv)):
        for m in re.findall(r"-?\d+", x):
            if int(m) not in (i, v, s, t):
                other_int = True
    if dv == s and ov == s and pv == s and not hedge:
        verdict = "FAITHFUL"
    elif dv == t or ov == t or pv == t:
        verdict = "CORRECTED"
    elif hedge or other_int:
        verdict = "FLAGGED"
    else:
        verdict = "DEVIANT"
    rows.append((i, s, t, dv, ov, pv, verdict))

# corpus-wide hedge scan
all_hedge = [i for i in range(240) if hedge_scan(DUMP[i]["sentence"])
             or hedge_scan(TEACH[i]["observation"])
             or hedge_scan(TEACH[i]["distractor"])
             or hedge_scan(TEACH[i]["probe"])]

L = []
L.append("# ERROR INVENTORY — STEP championship English corpus (step-3.7-flash:free)")
L.append("")
L.append(f"Source: `corpus.json` (sha256 `{SHA}`),")
L.append(f"generated by `build/gen_corpus.py` on 2026-09-21, model `{meta['model']}`,")
L.append("temperature 0, seed 42 (seed accepted by API; honor not externally verifiable).")
L.append("Prompts frozen and programmatic: the frozen batch prompts under")
L.append("`corpus-input/prompts/` (verified sha256 against `corpus-input/SHA256SUMS.txt`).")
L.append("")
L.append("## 1. Mechanical inventory (model text vs supplied input claims, all 240 ids)")
L.append("")
L.append("| check | definition | count |")
L.append("|---|---|---|")
L.append(f"| E_dump | dump VALUE != supplied input claim | {len(E_dump)} |")
L.append(f"| E_obs | teach OBS_VALUE != supplied input claim | {len(E_obs)} |")
L.append(f"| E_prb | teach PROBE_VALUE != supplied input claim | {len(E_prb)} |")
L.append(f"| inconsistent | obs_value != probe_value for the same id | {len(INCONS)} |")
L.append(f"| sentence_missing_value | dump/obs/distract/probe text does not contain its asserted value | {len(missing)} |")
L.append(f"| distractor-equals-obs | DISTRACT_VALUE == OBS_VALUE (intentionally different by design) | {len(DIST_EQ_OBS)} |")
L.append("")
L.append("The distractor differs from the observation on "
         f"{240-len(DIST_EQ_OBS)}/240 ids (by design: it is the competing directive")
L.append("the D2 learner must filter, not a model error).")
for sec, ids in (("E_dump", E_dump), ("E_obs", E_obs), ("E_prb", E_prb),
                 ("inconsistent", INCONS), ("distractor-equals-obs", DIST_EQ_OBS)):
    if ids:
        L.append(f"- {sec} ids: {ids}")
for sec, i in missing:
    L.append(f"- missing-value: {sec} id {i}")
L.append("")
L.append("## 2. The 12 deliberately false ids")
L.append("")
L.append("Deliberately false ids: {3, 29, 55, 71, 80, 103, 117, 139, 163, 178, 205, 231}.")
L.append("For each, the input claim is a falsehood about real English facts; the question")
L.append("is whether the model reproduced it faithfully or flagged/corrected it.")
L.append("")
L.append("| id | input claim | true value | dump VALUE | teach OBS_VALUE | teach PROBE_VALUE | verdict |")
L.append("|---|---|---|---|---|---|---|")
for i, s, t, dv, ov, pv, verdict in rows:
    L.append(f"| {i} | {s} | {t} | {dv} | {ov} | {pv} | {verdict} |")
L.append("")
L.append("Semantic scan method: every dump sentence, teach observation, distractor and")
L.append("probe text for these 12 ids was scanned for correction/hedge signals")
L.append("(actually, incorrect, however, disputed, false, error, mistake, correction)")
L.append("and for any asserted integer other than the fact id, the supplied claim, the")
L.append("true value, and the asserted VALUE. Corpus-wide hedge-signal scan:")
L.append(f"{len(all_hedge)} ids with any signal: {all_hedge}.")
L.append("")
faithful = sum(1 for r in rows if r[6] == "FAITHFUL")
L.append(f"Result: **{faithful}/12 false ids reproduced exactly as supplied**; "
         f"{12-faithful}/12 flagged/corrected. (The false ids are a trap for the D2")
L.append("learner's eliminative verification, not for the model.)")
L.append("")
L.append("## 3. Comparison with the toy step run")
L.append("")
L.append("The toy Zharovia step-3.7-flash corpus (q2-distillation-step37) had 0 deviations")
L.append("in 240 ids (E_dump=E_obs=E_prb=0, 12/12 false ids FAITHFUL). This English corpus:")
L.append(f"E_dump={len(E_dump)}/240, E_obs={len(E_obs)}/240, E_prb={len(E_prb)}/240, "
         f"false-id faithful={faithful}/12.")
L.append("")
L.append("## 4. Collection notes (mechanical, content-neutral)")
L.append("")
L.append("- 40 batches (20 dump + 20 teach), one LLM call per batch.")
L.append("- Parse retries: only mechanical parse failures, max 2 per batch.")
L.append("- No semantic retry occurred.")
L.append("- Transient HTTP 429/503 paced with 90-second waits per the night-run precedent.")
L.append("- Raw batches hashed individually (`corpus/raw/SHA256SUMS.txt`); corpus hash")
L.append("  recorded in `corpus/SHA256.txt` and `corpus/SHA256SUMS.txt`.")

out = os.path.join(STEP, "corpus", "ERROR_INVENTORY.md")
open(out, "w").write("\n".join(L) + "\n")
print("\n".join(L))
print(f"\nwrote {out}")
