#!/usr/bin/env python3
"""Generate swe_corpus.zag from the frozen english corpus.json.

Reads:  ../corpus/corpus.json  (frozen, sha256-verified against
        ../corpus/SHA256.txt)
        ../../corpus-input/facts.json (frozen input: SUPPLIED values +
        false-id set)
Writes: ../legs/legA/src/swe_corpus.zag
        ../legs/legB/src/swe_corpus.zag
        ../legs/legC/src/swe_corpus.zag   (byte-identical copies)

Accessors:
  swe_truth_at(id) = TRUE value (facts.json supplied for the 228 true ids;
                     ground_truth_notes.md true values for the 12 false ids)
  swe_claim_at(id) = SUPPLIED (trainer-given) value from facts.json
  swe_dump_at(id)  = model's dump VALUE for id (from the frozen LLM output)
  swe_obs_at(id)   = model's teach OBS_VALUE
  swe_dis_at(id)   = model's teach DISTRACT_VALUE
  swe_prb_at(id)   = model's teach PROBE_VALUE
SWE_CORPUS_SHA256 = sha256 of the frozen corpus.json.

The legs teach the LLM's frozen teaching sequence (swe_obs_at etc.) and use
swe_claim_at as the trainer-supplied record; swe_truth_at is the
harness-side world truth (used by t5_truth via t5_core.zag, and by phase-2
disproof / analysis). No RNG; literal if/else chains only.
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SWE = os.path.dirname(HERE)
CORPUS_JSON = os.path.join(SWE, "corpus", "corpus.json")
CORPUS_SHA = os.path.join(SWE, "corpus", "SHA256.txt")
FACTS_JSON = os.path.join(SWE, "..", "corpus-input", "facts.json")

raw = open(CORPUS_JSON, "rb").read()
sha = hashlib.sha256(raw).hexdigest()
expect = open(CORPUS_SHA).read().strip()
assert sha == expect, f"corpus.json sha256 mismatch: {sha} != {expect}"
corpus = json.loads(raw.decode("utf-8"))
assert corpus["meta"]["model"] == "swe-1-6-slow:free", "model drift"
assert corpus["meta"]["temperature"] == 0, "temperature drift"
assert corpus["meta"]["prompts_sha256"] == \
    "ac5d7d3155f9a90dc60f4f3ec529a3c6125a0469ce5862c7193fb261441b8b7d", \
    "prompts sha drift"

facts = json.load(open(FACTS_JSON))
FALSE_IDS = set(facts["false_ids"])
assert FALSE_IDS == {3, 29, 55, 71, 80, 103, 117, 139, 163, 178, 205, 231}
SUPPLIED = {i: facts[str(i)]["value"] for i in range(240)}

# TRUE values: frozen ground_truth_notes.md (verified 2026-09-21).
TRUE_FALSE = {3: 4, 29: 4, 55: 8, 71: 20, 80: 9, 103: 1678,
              117: 1850, 139: 1895, 163: 3, 178: 9, 205: 37, 231: 8}
TRUTH = {i: (TRUE_FALSE[i] if i in FALSE_IDS else SUPPLIED[i])
         for i in range(240)}

# input_claims in corpus.json must equal the frozen SUPPLIED values
for i in range(240):
    assert corpus["input_claims"][str(i)] == SUPPLIED[i], \
        f"input_claim drift at {i}"

DUMP = {e["id"]: e["value"] for e in corpus["dump"]}
OBS = {e["id"]: e["obs_value"] for e in corpus["teach"]}
DIS = {e["id"]: e["distract_value"] for e in corpus["teach"]}
PRB = {e["id"]: e["probe_value"] for e in corpus["teach"]}
assert len(DUMP) == len(OBS) == len(DIS) == len(PRB) == 240

facts_sha = hashlib.sha256(open(FACTS_JSON, "rb").read()).hexdigest()


def chain(fn, table):
    """240-entry if/else chain in chunks of 20 (same pattern as the
    muse build_gen.py: each chunk is if/else-if/.../else{, the final
    chunk closes with else{return -1;}, then all braces close)."""
    out = [f"fn {fn}(id:i32)i32 {{"]
    for c0 in range(0, 240, 20):
        chunk = list(range(c0, min(c0 + 20, 240)))
        expr = "".join(f"if(id=={i}){{return {table[i]};}}else "
                       for i in chunk)
        expr += "{return -1;}" if c0 + 20 >= 240 else "{"
        out.append("    " + expr)
    out.append("}" * 12)  # 11 chunk braces + fn brace
    body = "\n".join(out)
    assert body.count("{") == body.count("}"), f"brace imbalance in {fn}"
    assert sum(1 for i in range(240) if f"if(id=={i})" in body) == 240, \
        f"id coverage drift in {fn}"
    return body


parts = []
parts.append("// swe_corpus.zag — GENERATED by build/build_corpus_zag.py. DO NOT EDIT.")
parts.append(f"// corpus: english-championship-v1, model swe-1-6-slow:free, temp 0")
parts.append(f"// corpus.json sha256: {sha}")
parts.append(f"// facts.json sha256:  {facts_sha}")
parts.append(f'const SWE_CORPUS_SHA256:[]u8="{sha}";')
parts.append(f'const SWE_FACTS_SHA256:[]u8="{facts_sha}";')
parts.append(chain("swe_truth_at", TRUTH))
parts.append(chain("swe_claim_at", SUPPLIED))
parts.append(chain("swe_dump_at", DUMP))
parts.append(chain("swe_obs_at", OBS))
parts.append(chain("swe_dis_at", DIS))
parts.append(chain("swe_prb_at", PRB))
text = "\n".join(parts) + "\n"

for leg in ("legA", "legB", "legC"):
    dest = os.path.join(SWE, "legs", leg, "src", "swe_corpus.zag")
    with open(dest, "w") as f:
        f.write(text)
    print(f"wrote {dest} ({len(text)} bytes)")

print("swe_corpus.zag: 6 accessors x 240 ids, "
      f"SWE_CORPUS_SHA256={sha[:16]}...")
