#!/usr/bin/env python3
"""gen_mw_c.py — generate authority/src/mw_cases_c.zag for arm C.

Reuses the frozen live envelopes (live/*.json) and golds (golds.json) via
gen_mw's frozen mechanical pieces (QUESTIONS, extract, recency_of,
load_results, derive). Arm C feeds the SAME per-question result rows as arm B
(feedC_* mirrors feedB_* byte-for-byte in content) but deliberates with
mw_deliberate_c (PRIMARY rule, PREREG-MW-C M1).

Expectations: the frozen PRIMARY rule is implemented here in Python
(primary_expected); if it fires the expected verdict is (CONVERGE, A,
PRIMARY), else arm B's frozen derive() output. The independent oracle
(verify_mw_c.py) reimplements both separately.
"""
import json
import os
import re
import sys

BASE = os.path.expanduser("~/workspace/tnn-lab/mixed-web")
sys.path.insert(0, BASE)
from gen_mw import QUESTIONS, derive, load_results, zc, zg  # noqa

OUT = os.path.join(BASE, "authority", "src", "mw_cases_c.zag")


def domain_label(dom):
    d = dom.lower()
    if d.startswith("www."):
        d = d[4:]
    return d.split(".")[0]


def primary_expected(question, results):
    """Frozen PREREG-MW-C M1 PRIMARY rule, literal reading.

    Returns (fires, answer). Fires iff: exactly one distinct domain's label
    equals a question token (len>=4); its newest answered assertion has
    recency>=2000 equal to the global max recency over all results; and
    (corroboration by another domain) OR (no other domain asserts a different
    answer at that same max recency).
    """
    toks = set(t for t in re.split(r"[^a-z]", question.lower()) if len(t) >= 4)
    doms = []
    for r in results:
        if r["domain"] not in doms:
            doms.append(r["domain"])
    prim = [d for d in doms if domain_label(d) in toks]
    if len(prim) != 1:
        return (False, "")
    D = prim[0]
    answered = [r for r in results if r["domain"] == D and r["answer"]]
    if not answered:
        return (False, "")
    rp = max(r["recency"] for r in answered)
    A = next(r["answer"] for r in answered if r["recency"] == rp)
    if rp < 2000:
        return (False, "")
    gmax = max(r["recency"] for r in results) if results else 0
    if rp != gmax:
        return (False, "")
    # condition 4: corroboration OR no equally-new contradiction (literal i.e.)
    if any(r["domain"] != D and r["answer"] == A for r in results):
        return (True, A)
    if any(r["domain"] != D and r["recency"] == gmax and r["answer"] != A
           for r in results):
        return (False, "")
    return (True, A)


def emit_feedC(lines, qid, question, temporal, results):
    lines.append(f"fn feedC_{qid}(w:*MwF) void {{")
    lines.append(f'    mw_fact_begin(w, "{qid}", "{zg(question)}", {temporal});')
    for r in results:
        lines.append(
            f'    mw_add_result(w, "{zg(r["domain"])}", "{zg(r["answer"])}", {r["recency"]});')
    lines.append("    return;")
    lines.append("}")


def emit_qc(lines, qid, exp_verdict, exp_chosen, exp_rule):
    lines.append(f"fn qc_{qid}() i32 {{")
    lines.append("    let w:*MwF=mw_new();")
    lines.append(f"    feedC_{qid}(w);")
    lines.append("    let v:i32=mw_deliberate_c(w);")
    lines.append("    mw_fact_end(w);")
    lines.append('    _zag_print("V|C|");')
    lines.append(f'    _zag_print("{qid}|");')
    lines.append('    if(v==1){_zag_print("CONVERGE|");}else{_zag_print("WITHHOLD|");}')
    lines.append('    _zag_print(w.*.chosen);_zag_print("|");')
    lines.append('    _zag_print(w.*.rule);_zag_print("|");')
    lines.append('    _zag_print(mw_chain(w));_zag_print("|");')
    lines.append('    if(mw_equal(w.*.rule,"PRIMARY")==1){_zag_print(mw_primary_cite_of(w));}else{_zag_print(mw_supp(w,w.*.chosen));}')
    lines.append('    _zag_print("|");')
    lines.append('    _zag_print(mw_head(w));_zag_println("");')
    lines.append("    let ok:i32=1;")
    if exp_verdict == "CONVERGE":
        lines.append("    if(v!=1){ok=0;}")
        lines.append(f'    if(mw_equal(w.*.chosen, "{zg(exp_chosen)}")!=1){{ok=0;}}')
    else:
        lines.append("    if(v!=2){ok=0;}")
    lines.append(f'    if(mw_equal(w.*.rule, "{exp_rule}")!=1){{ok=0;}}')
    lines.append("    return ok;")
    lines.append("}")


def main():
    golds = json.load(open(os.path.join(BASE, "golds.json")))
    kept = golds["kept"]
    lines = ["// mw_cases_c.zag — GENERATED by gen_mw_c.py. Do not hand-edit.",
             "// Feeds reuse the frozen live envelopes (same rows as arm B's feedB_*);",
             "// deliberation is arm C (mw_deliberate_c). Expectations: frozen PRIMARY",
             "// rule (PREREG-MW-C M1), else arm B's frozen derive().",
             '@import("mw_sense_c.zag")', ""]
    manifest = []
    qids = []
    fires = []
    for qid, question, temporal, cands in QUESTIONS:
        if qid not in kept:
            continue
        results, _disc = load_results(qid, cands)
        verdict, chosen, rule, cls, _ct = derive(temporal, results)
        pf, pa = primary_expected(question, results)
        if pf:
            verdict, chosen, rule = "CONVERGE", pa, "PRIMARY"
            fires.append(qid)
        emit_feedC(lines, qid, question, temporal, results)
        emit_qc(lines, qid, verdict, chosen, rule)
        qids.append(qid)
        manifest.append(f"{qid}: expected={verdict} chosen={chosen or '-'} "
                        f"rule={rule} primary_fires={pf}")
    lines.append("fn run_c_all() i32 {")
    lines.append("    let p:i32=1;")
    for qid in qids:
        lines.append(f"    if(qc_{qid}()!=1){{p=0;}}")
    lines.append("    return p;")
    lines.append("}")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(lines)} lines, {len(qids)} questions kept")
    print(f"PRIMARY fires on: {fires if fires else 'NONE'}")
    print("\n".join(manifest))


if __name__ == "__main__":
    main()
