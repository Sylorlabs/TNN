# ------------------------------------------------------- binary writers
def write_img(path, w, h, px):
    """px: (h*w,3) uint8 array."""
    with open(path, "wb") as f:
        f.write(struct.pack("<II", w, h))
        f.write(np.ascontiguousarray(px, dtype=np.uint8).tobytes())

def write_pcm(path, rate, samples):
    """samples: int16 array."""
    s = np.ascontiguousarray(samples, dtype=np.int16)
    with open(path, "wb") as f:
        f.write(struct.pack("<II", rate, len(s)))
        f.write(s.tobytes())

def write_vid(path, w, h, frames):
    """frames: list of (h*w,3) uint8 arrays."""
    with open(path, "wb") as f:
        f.write(struct.pack("<III", len(frames), w, h))
        for fr in frames:
            f.write(np.ascontiguousarray(fr, dtype=np.uint8).tobytes())

def write_truth(path, value):
    with open(path + ".truth", "w") as f:
        f.write("truth=%s\n" % value)

