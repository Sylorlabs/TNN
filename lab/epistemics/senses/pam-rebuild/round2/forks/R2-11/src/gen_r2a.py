def srgb_to_linear(c):
    c = np.asarray(c, dtype=np.float64) / 255.0
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)

def linear_to_srgb(c):
    c = np.clip(np.asarray(c, dtype=np.float64), 0.0, 1.0)
    v = np.where(c <= 0.0031308, 12.92 * c, 1.055 * (c ** (1.0 / 2.4)) - 0.055)
    return np.clip(np.round(v * 255), 0, 255).astype(np.uint8)

XYZ_M = np.array(((0.4124564, 0.3575761, 0.1804375),
                  (0.2126729, 0.7151522, 0.0721750),
                  (0.0193339, 0.1191920, 0.9503041)))
XYZ_MI = np.array((( 3.2404542, -1.5371385, -0.4985314),
                   (-0.9692660,  1.8760108,  0.0415560),
                   ( 0.0556434, -0.2040259,  1.0572252)))
BRAD = np.array(((0.8951, 0.2664, -0.1614),
                 (-0.7502, 1.7135, 0.0367),
                 (0.0389, -0.0685, 1.0296)))
BRAD_I = np.array(((0.9869929, -0.1470543, 0.1599627),
                   (0.4323053, 0.5183603, 0.0492912),
                   (-0.0085287, 0.0400428, 0.9684867)))

def rgb_to_xyz_np(rgb):
    lin = srgb_to_linear(rgb)
    return lin @ XYZ_M.T

def apply_illuminant_np(rgb, illum_xyz):
    """Vectorized von-Kries (Bradford CAT). rgb: (N,3) uint8 -> (N,3) uint8."""
    xyz = rgb_to_xyz_np(rgb.astype(np.float64))
    src = np.array((0.95047, 1.0, 1.08883))
    dst = np.array(illum_xyz)
    lms_s = xyz @ BRAD.T
    lms_wsrc = src @ BRAD.T
    lms_wdst = dst @ BRAD.T
    lms = lms_s * (lms_wdst / lms_wsrc)
    xa = lms @ BRAD_I.T
    lin = xa @ XYZ_MI.T
    return linear_to_srgb(lin)

# scalar versions for the dE search (single colors)
def _srgb_lin_1(c):
    c /= 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

def _lin_srgb_1(c):
    c = max(0.0, min(1.0, c))
    v = 12.92 * c if c <= 0.0031308 else 1.055 * (c ** (1.0 / 2.4)) - 0.055
    return int(round(max(0.0, min(1.0, v)) * 255))

def rgb_to_lab_1(r, g, b):
    rl, gl, bl = _srgb_lin_1(r), _srgb_lin_1(g), _srgb_lin_1(b)
    x = 0.4124564*rl + 0.3575761*gl + 0.1804375*bl
    y = 0.2126729*rl + 0.7151522*gl + 0.0721750*bl
    z = 0.0193339*rl + 0.1191920*gl + 0.9503041*bl
    xn, yn, zn = 0.95047, 1.0, 1.08883
    def f(t):
        return t ** (1/3) if t > 0.008856 else 7.787 * t + 16/116
    fx, fy, fz = f(x/xn), f(y/yn), f(z/zn)
    return (116*fy - 16, 500*(fx - fy), 200*(fy - fz))

def delta_e_2000(lab1, lab2):
    L1, a1, b1 = lab1; L2, a2, b2 = lab2
    kL = kC = kH = 1.0
    C1 = math.hypot(a1, b1); C2 = math.hypot(a2, b2)
    Cb = (C1 + C2) / 2
    G = 0.5 * (1 - math.sqrt(Cb**7 / (Cb**7 + 25**7)))
    ap1 = (1 + G) * a1; ap2 = (1 + G) * a2
    Cp1 = math.hypot(ap1, b1); Cp2 = math.hypot(ap2, b2)
    def hp(ap, b):
        if ap == 0 and b == 0: return 0.0
        h = math.degrees(math.atan2(b, ap))
        return h + 360 if h < 0 else h
    hp1, hp2 = hp(ap1, b1), hp(ap2, b2)
    dL = L2 - L1; dC = Cp2 - Cp1
    if Cp1 * Cp2 == 0:
        dh = 0.0
    else:
        dh = hp2 - hp1
        if dh > 180: dh -= 360
        elif dh < -180: dh += 360
    dH = 2 * math.sqrt(Cp1 * Cp2) * math.sin(math.radians(dh / 2))
    Lbp = (L1 + L2) / 2; Cbp = (Cp1 + Cp2) / 2
    if Cp1 * Cp2 == 0:
        hbp = hp1 + hp2
    else:
        hbp = (hp1 + hp2) / 2 if abs(hp1 - hp2) <= 180 else (hp1 + hp2 + 360) / 2 if hp1 + hp2 < 360 else (hp1 + hp2 - 360) / 2
    T = (1 - 0.17*math.cos(math.radians(hbp-30)) + 0.24*math.cos(math.radians(2*hbp))
         + 0.32*math.cos(math.radians(3*hbp+6)) - 0.20*math.cos(math.radians(4*hbp-63)))
    dRo = 30 * math.exp(-((hbp - 275) / 25) ** 2)
    Rc = 2 * math.sqrt(Cbp**7 / (Cbp**7 + 25**7))
    Sl = 1 + 0.015 * (Lbp - 50) ** 2 / math.sqrt(20 + (Lbp - 50) ** 2)
    Sc = 1 + 0.045 * Cbp
    Sh = 1 + 0.015 * Cbp * T
    Rt = -math.sin(math.radians(2 * dRo)) * Rc
    return math.sqrt((dL/(kL*Sl))**2 + (dC/(kC*Sc))**2 + (dH/(kH*Sh))**2 + Rt*(dC/(kC*Sc))*(dH/(kH*Sh)))

def _lab_to_srgb_1(L, a, b):
    xn, yn, zn = 0.95047, 1.0, 1.08883
    fy = (L + 16) / 116.0
    fx = fy + a / 500.0
    fz = fy - b / 200.0
    def fi(t):
        return t**3 if t**3 > 0.008856 else (t - 16/116) / 7.787
    x, y, z = xn*fi(fx), yn*fi(fy), zn*fi(fz)
    rl = 3.2404542*x - 1.5371385*y - 0.4985314*z
    gl = -0.9692660*x + 1.8760108*y + 0.0415560*z
    bl = 0.0556434*x - 0.2040259*y + 1.0572252*z
    return (_lin_srgb_1(rl), _lin_srgb_1(gl), _lin_srgb_1(bl))

def _rand_color(rng):
    return (rng.int(256), rng.int(256), rng.int(256))

def _color_at_distance(rng, base, target_de, tol=0.15, tries=400):
    L0, a0, b0 = rgb_to_lab_1(*base)
    best = None
    for _ in range(tries):
        ang = rng.uniform() * 2 * math.pi
        step = target_de * rng.range(0.35, 0.7)
        L1 = max(0.0, min(100.0, L0 + step * math.cos(ang) * rng.range(0.4, 1.0)))
        C = step * math.sin(ang)
        a1 = a0 + C * math.cos(rng.uniform() * 2 * math.pi)
        b1 = b0 + C * math.sin(rng.uniform() * 2 * math.pi)
        rgb = _lab_to_srgb_1(L1, a1, b1)
        de = delta_e_2000((L0, a0, b0), rgb_to_lab_1(*rgb))
        if abs(de - target_de) / max(target_de, 1e-9) < tol:
            return rgb
        if best is None or abs(de - target_de) < abs(best[0] - target_de):
            best = (de, rgb)
    return best[1]

