def _raster_shape(kind, W, cx, cy, scale, rot, fg, bg_px, occl_bar):
    """Vectorized 3x3-supersampled rasterization. bg_px: (W*W,3) uint8."""
    SS = 3
    ys, xs = np.mgrid[0:W, 0:W]
    sub = (np.arange(SS) + 0.5) / SS - 0.5   # subpixel offsets
    # coverage accumulator
    cov = np.zeros((W, W))
    cosr, sinr = math.cos(rot), math.sin(rot)
    for sy in sub:
        for sx in sub:
            fx = xs + sx - cx
            fy = ys + sy - cy
            ux = (fx * cosr + fy * sinr) / scale
            uy = (-fx * sinr + fy * cosr) / scale
            if kind == "circle":
                hit = (ux*ux + uy*uy) <= 0.25
            elif kind == "square":
                hit = (np.abs(ux) <= 0.5) & (np.abs(uy) <= 0.5)
            else:  # triangle
                R = 0.62
                angs = np.array([math.pi/2 + k*2*math.pi/3 for k in range(3)])
                vx = R * np.cos(angs); vy = -R * np.sin(angs)
                def sgn(px, py, ax, ay, bx, by):
                    return (px-bx)*(ay-by) - (ax-bx)*(py-by)
                d1 = sgn(ux, uy, vx[0], vy[0], vx[1], vy[1])
                d2 = sgn(ux, uy, vx[1], vy[1], vx[2], vy[2])
                d3 = sgn(ux, uy, vx[2], vy[2], vx[0], vy[0])
                neg = (d1 < 0) | (d2 < 0) | (d3 < 0)
                pos = (d1 > 0) | (d2 > 0) | (d3 > 0)
                hit = ~(neg & pos)
            cov += hit.astype(np.float64)
    a = (cov / (SS*SS))[..., None]
    fg_a = np.asarray(fg, dtype=np.float64)
    bg_a = bg_px.reshape(W, W, 3).astype(np.float64)
    px = fg_a * a + bg_a * (1 - a)
    if occl_bar:
        bar = np.zeros((W, W, 3))
        bar[30:45, :, :] = bg_a[30:45, :, :] * 0.9 + 40
        m = np.zeros((W, W, 1)); m[30:45, :, :] = 1.0
        px = px * (1 - m) + bar * m
    return np.clip(np.round(px), 0, 255).astype(np.uint8).reshape(-1, 3)

