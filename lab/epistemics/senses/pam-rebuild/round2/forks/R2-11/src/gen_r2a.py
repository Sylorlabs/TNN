SR = 16000

def _tone_np(freq, dur, harmonics, amp=0.75):
    """harmonics: list of (multiple, amplitude). 20ms raised-cosine ramps."""
    n = int(SR * dur)
    t = np.arange(n, dtype=np.float64) / SR
    out = np.zeros(n)
    for k, a in harmonics:
        out += a * np.sin(2 * np.pi * freq * k * t)
    ramp = int(SR * 0.02)
    env = np.ones(n)
    r = 0.5 - 0.5 * np.cos(np.pi * np.arange(ramp) / ramp)
    env[:ramp] = r
    env[n-ramp:] = r[::-1]
    out *= env
    peak = np.max(np.abs(out))
    g = (amp / peak) * 32767 if peak > 1e-9 else 0.0
    return np.clip(np.round(out * g), -32768, 32767).astype(np.int16)

def _glide_tone_np(f_start, f_end, dur, harmonics, amp=0.75):
    """Linear frequency glide via phase accumulation."""
    n = int(SR * dur)
    t = np.arange(n, dtype=np.float64) / SR
    f = f_start + (f_end - f_start) * (t / dur)
    phase = 2 * np.pi * np.cumsum(f) / SR
    out = np.zeros(n)
    for k, a in harmonics:
        out += a * np.sin(k * phase)
    ramp = int(SR * 0.02)
    env = np.ones(n)
    r = 0.5 - 0.5 * np.cos(np.pi * np.arange(ramp) / ramp)
    env[:ramp] = r
    env[n-ramp:] = r[::-1]
    out *= env
    peak = np.max(np.abs(out))
    g = (amp / peak) * 32767 if peak > 1e-9 else 0.0
    return np.clip(np.round(out * g), -32768, 32767).astype(np.int16)

