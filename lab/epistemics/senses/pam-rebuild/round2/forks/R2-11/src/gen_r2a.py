def _motion_frames(rng, photo, vec, step, contrast, ox, oy, W=64, nframes=8):
    im = photo.reshape(120, 160, 3).astype(np.float64)
    mean = im.reshape(-1, 3).mean(axis=0)
    imc = mean + (im - mean) * contrast
    imc = np.clip(np.round(imc), 0, 255).astype(np.uint8)
    frames = []
    yy, xx = np.mgrid[0:W, 0:W]
    for f in range(nframes):
        dx = int(round(-vec[0] * step * f)); dy = int(round(-vec[1] * step * f))
        sx = (ox + xx + dx) % 160
        sy = (oy + yy + dy) % 120
        frames.append(imc[sy, sx].reshape(-1, 3).copy())
    return frames

