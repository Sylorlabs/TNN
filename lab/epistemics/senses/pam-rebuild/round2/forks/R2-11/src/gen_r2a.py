def _centroid(harm, f0=440.0):
    num = sum(k * f0 * a for k, a in harm)
    den = sum(a for _, a in harm)
    return num / den if den > 0 else 0.0

CENTROIDS = {c: _centroid(h) for c, h in TIMBRES.items()}

def _nearest_class(cent):
    return min(CENTROIDS, key=lambda c: abs(CENTROIDS[c] - cent))

def _exp_profile_for_centroid(target, f0=440.0):
    """Harmonic profile (exponential rolloff 1..8) with spectral centroid
    == target Hz. Solved by bisection on the rolloff rate (deterministic)."""
    def cent_of(s):
        harm = [(k, math.exp(-(k-1)*s)) for k in range(1, 9)]
        return _centroid(harm, f0)
    lo, hi = -0.5, 4.0   # s=-0.5 -> rising harmonics (bright); s=4 -> ~pure
    for _ in range(60):
        mid = (lo + hi) / 2
        if cent_of(mid) < target:
            hi = mid
        else:
            lo = mid
    s = (lo + hi) / 2
    return [(k, math.exp(-(k-1)*s)) for k in range(1, 9)]

