def sha_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for ch in iter(lambda: f.read(1 << 20), b""):
            h.update(ch)
    return h.hexdigest()

def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "fixtures")
    only = sys.argv[2] if len(sys.argv) > 2 else None
    manifest = []
    dist = {}
    for task in TASKS:
        if only and task != only:
            continue
        for variant, counts, fns in (("normal", NORMAL_COUNTS, NORMAL_FN),
                                     ("adversarial", ADV_COUNTS, ADV_FN)):
            d = os.path.join(root, variant, task)
            os.makedirs(d, exist_ok=True)
            n = counts[task]
            truths = {}
            for i in range(n):
                t = fns[task](i, d)
                truths[t] = truths.get(t, 0) + 1
            dist[(task, variant)] = (n, truths)
            print("%s/%s: %d %s" % (task, variant, n, truths), flush=True)
    # manifest over every generated byte (+ truth files)
    for task in TASKS:
        if only and task != only:
            continue
        for variant in ("normal", "adversarial"):
            d = os.path.join(root, variant, task)
            for fn in sorted(os.listdir(d)):
                fp = os.path.join(d, fn)
                rel = os.path.relpath(fp, root)
                manifest.append((sha_file(fp), rel))
    man_path = os.path.join(root, "MANIFEST.sha256")
    with open(man_path, "w") as f:
        for sha, rel in manifest:
            f.write("%s  %s\n" % (sha, rel))
    total = sum(n for (n, _) in dist.values())
    print("TOTAL generated: %d  (+740 frozen normal +185 frozen adversarial = %d pool)"
          % (total, total + 925), flush=True)
    print("MANIFEST: %s (%d entries)" % (man_path, len(manifest)), flush=True)

if __name__ == "__main__":
    main()
