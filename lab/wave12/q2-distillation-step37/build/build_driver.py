#!/usr/bin/env python3
"""Assemble src/s37_trial.zag from src/q2s_trial.zag + src/s37_step.zag.

The Q2/sol trial body is kept verbatim (only the corpus import is swapped to
s37_corpus.zag and the Q1 §B.7 sources are added to the import block); the
STEP header, flaw4/teach3 dispatch, and the appended s37_step.zag carry the
championship-team additions. Reruns must be byte-identical.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "src")

with open(os.path.join(SRC, "q2s_trial.zag")) as f:
    body = f.read()
with open(os.path.join(SRC, "s37_step.zag")) as f:
    step = f.read()

HEADER = """\
// s37_trial.zag — championship team STEP driver (ASSEMBLED — do not edit;
// edit src/q2s_trial.zag, src/s37_step.zag, or build/build_driver.py).
//
// Provenance:
//   * Q2/sol trial body: VERBATIM copy of src/q2s_trial.zag (sha256
//     b93cb61bb72eec769b391e8a418e702b6a295cc89cc8d099efc0456a856e9a70),
//     itself the sol-leg replication of Q2's instruments per
//     prereg/PREREG_Q2_DISTILLATION.md (frozen).
//   * Corpus: src/s37_corpus.zag (frozen step-3.7-flash corpus, sha256
//     bd1cbe59c3e776d1bc6f63c9a83cba408fd6e91684a28029be922311dbd4a02d)
//     replaces src/q2_corpus.zag in the import block.
//   * Q1 §B.7 sources (q1_types/proposal/tape/tripwire/flawscore/world/
//     learner): verbatim from q1b-teacher-bakeoff (2026-09-21), added to the
//     import block. Zero symbol collisions with the Q2 body (verified).
//   * STEP additions: flaw4/teach3 dispatch in main() + src/s37_step.zag
//     appended below (class-4 separate+direct, class-3 teach, teacher id 20).
//
// Modes (argv[1]): bind, btrap (Q2/sol, unchanged) | flaw4 <label> <rep>
// (class 4: D2-taught learner judges the sealed §B.7 schedule directly) |
// teach3 <label> <rep> (class 3: taught learner becomes teacher id 20 for a
// fresh arm-B learner). Exit code = failed internal checks. N=5 runs of any
// mode must be byte-identical. Pure Zag, zero RNG.
"""

# 1b. S37 §P delta: generate src/q1_proposal_s37.zag = verbatim
# q1_proposal.zag + the STEP teacher-id allowlist extension (TB_TID_S37=20,
# first id in the 20s). The session seq-tracking default branch (last5)
# already handles a single-teacher session correctly, so no change needed
# there. src/q1_proposal.zag itself stays verbatim.
with open(os.path.join(SRC, "q1_proposal.zag")) as f:
    qp = f.read()
S37_QP_HEADER = """\
// q1_proposal_s37.zag — GENERATED by build/build_driver.py. Do not edit.
// Verbatim copy of src/q1_proposal.zag (sha256
// ed90b0f3d89a89dec752822485472a2ab24c65ba193f9eb8c6349f9631d2f2d)
// with ONE documented S37 delta: TB_TID_S37=20 added to the §P ingress
// teacher-id allowlist (championship team STEP: the D2-taught learner
// teaches as teacher id 20, first id in the 20s; Q1 used 6, Q1B used 7).
// The allowlist is the protocol's teacher-identity gate; extending it for
// a new teacher is the documented mechanism (cf. the Q1/Q1B deltas kept
// verbatim below).
const TB_TID_S37:i64=20;
"""
old_tid = "    // Q1B delta: TB_TID_LEARNED(7) accepted as well.\n"
new_tid = ("    // Q1B delta: TB_TID_LEARNED(7) accepted as well.\n"
           "    // S37 delta: TB_TID_S37(20) accepted as well.\n")
assert qp.count(old_tid) == 1, "tid comment anchor not found"
qp = qp.replace(old_tid, new_tid)
old_allow = "if(tid!=TB_TID_PEER && tid!=TB_TID_MUSE && tid!=TB_TID_SYMHINT && tid!=TB_TID_SYMYN && tid!=TB_TID_PLANTED && tid!=TB_TID_LEARNED){"
new_allow = "if(tid!=TB_TID_PEER && tid!=TB_TID_MUSE && tid!=TB_TID_SYMHINT && tid!=TB_TID_SYMYN && tid!=TB_TID_PLANTED && tid!=TB_TID_LEARNED && tid!=TB_TID_S37){"
assert qp.count(old_allow) == 1, "allowlist anchor not found"
qp = qp.replace(old_allow, new_allow)
qp_path = os.path.join(SRC, "q1_proposal_s37.zag")
with open(qp_path, "w") as f:
    f.write(S37_QP_HEADER + qp)
print(f"wrote {qp_path} ({os.path.getsize(qp_path)} bytes)")

# 1. import block: swap corpus, add Q1 sources
old_imp = '@import("q2_corpus.zag")'
new_imp = ('@import("s37_corpus.zag")\n'
           '@import("q1_types.zag")\n'
           '@import("q1_proposal_s37.zag")\n'
           '@import("q1_tape.zag")\n'
           '@import("q1_tripwire.zag")\n'
           '@import("q1_flawscore.zag")\n'
           '@import("q1_world.zag")\n'
           '@import("q1_learner.zag")')
assert body.count(old_imp) == 1, "import anchor not found"
body = body.replace(old_imp, new_imp)

# 2. main(): usage + new dispatch branches
old_usage = '_zag_println("usage: q2t <bind <label> <armidx> <rep> <scale>|btrap <label> <armidx> <rep>>");'
new_usage = '_zag_println("usage: s37t <bind <label> <armidx> <rep> <scale>|btrap <label> <armidx> <rep>|flaw4 <label> <rep>|teach3 <label> <rep>>");'
assert body.count(old_usage) == 1, "usage anchor not found"
body = body.replace(old_usage, new_usage)

old_bind_usage = '_zag_println("usage: q2t bind <label> <armidx> <rep> <scale>");'
assert body.count(old_bind_usage) == 1
body = body.replace(old_bind_usage, '_zag_println("usage: s37t bind <label> <armidx> <rep> <scale>");')
old_btrap_usage = '_zag_println("usage: q2t btrap <label> <armidx> <rep>");'
assert body.count(old_btrap_usage) == 1
body = body.replace(old_btrap_usage, '_zag_println("usage: s37t btrap <label> <armidx> <rep>");')

anchor = '    _zag_println("unknown mode");'
assert body.count(anchor) == 1, "dispatch anchor not found"
branches = '''\
    if(nio_equal(mode,"flaw4")==1){
        if(_zag_argc()<4){
            _zag_println("usage: s37t flaw4 <label> <rep>");
            return 64;
        }
        return s37_flaw4(_zag_arg(2),q2_atoi(_zag_arg(3)));
    }
    if(nio_equal(mode,"teach3")==1){
        if(_zag_argc()<4){
            _zag_println("usage: s37t teach3 <label> <rep>");
            return 64;
        }
        return s37_teach3(_zag_arg(2),q2_atoi(_zag_arg(3)));
    }
'''
body = body.replace(anchor, branches + anchor)

out = HEADER + body + "\n" + step
out_path = os.path.join(SRC, "s37_trial.zag")
with open(out_path, "w") as f:
    f.write(out)
print(f"wrote {out_path} ({os.path.getsize(out_path)} bytes)")
